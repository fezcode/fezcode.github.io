const REPLACE = {
  ı: 'I',
  İ: 'I',
  '—': '-',
  '–': '-',
  '‘': "'",
  '’': "'",
  '“': '"',
  '”': '"',
  '…': '...',
  '×': 'X',
  '•': '·',
  '❤': '♥',
};

/** Turn any string into characters the stitch fonts can knit. */
export const normalizeText = (text, font = FONTS.big) =>
  [...String(text ?? '')]
    .map((ch) => REPLACE[ch] ?? ch)
    .join('')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .replace(/\s+/g, ' ')
    .split('')
    .filter((ch) => font.glyphs[ch])
    .join('');

export const glyphWidth = (ch, font) => font.glyphs[ch]?.[0].length ?? 0;

/** Width in stitches of a line of text (already normalized). */
export const textWidth = (text, font = FONTS.big, scale = 1) => {
  const chars = [...text];
  if (!chars.length) return 0;
  return (
    chars.reduce((n, ch) => n + glyphWidth(ch, font) + font.gap, -font.gap) *
    scale
  );
};

/** Break text into lines no wider than maxCols stitches. */
export const wrapText = (text, maxCols, font = FONTS.big, scale = 1) => {
  const lines = [];
  let line = '';
  const pushWord = (word) => {
    // a word too long for one line is split across lines
    let rest = word;
    while (textWidth(rest, font, scale) > maxCols && rest.length > 1) {
      let cut = rest.length - 1;
      while (cut > 1 && textWidth(rest.slice(0, cut), font, scale) > maxCols) cut--;
      lines.push(rest.slice(0, cut));
      rest = rest.slice(cut);
    }
    return rest;
  };
  text.split(' ').forEach((word) => {
    if (!word) return;
    const next = line ? `${line} ${word}` : word;
    if (textWidth(next, font, scale) <= maxCols) line = next;
    else {
      if (line) lines.push(line);
      line = pushWord(word);
    }
  });
  if (line) lines.push(line);
  return lines.length ? lines : [''];
};
